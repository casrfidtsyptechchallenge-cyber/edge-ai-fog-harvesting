#include <stdint.h>

// Novelty guard of the arc predictor (M5a): is this window like the ones the CNN was trained on?
// Three checks, the first that applies gives the reason (ml/arc_novelty.py is the reference):
//   kSaturated    4 samples or more equal to the window's maximum: the input is clipped (gain too high)
//   kOutOfRange   log(1 + pulses/s), log(noise), log(median µA) outside the range seen in training: another
//                 current scale, a dead or disconnected sensor, far more noise
//   kUnusualShape the CNN's 32 pooled features far from training (Mahalanobis distance above threshold)
// The node keeps the CNN's risk (the evaluation showed that switching to the rule makes things worse), sends the
// window as a NOVEL wave for M11, and reports the recent share of novel windows (telemetry arc_novel): the HV
// controller (M6) stops climbing while the model is out of its depth.
// Parameters: arc_novelty_data.h, GENERATED by python -m ml novelty for the model in arc_model_data.h.
struct ArcNovelty {
  enum Reason : uint8_t { kKnown = 0, kSaturated = 1, kOutOfRange = 2, kUnusualShape = 3 };
  Reason reason;
  float distance2;  // squared Mahalanobis distance of the shape; -1 when the CNN did not run

  bool novel() const { return reason != kKnown; }
  static const char* reasonName(Reason r);

  // pooled: the CNN's 32 pooled features, or nullptr when the CNN did not run (then no shape check).
  static ArcNovelty check(const int8_t* pooled, float pulsesPerS, float noise, float medianUa, int maxTies);
  static float shapeDistance2(const int8_t* pooled);
  static float threshold();
};
