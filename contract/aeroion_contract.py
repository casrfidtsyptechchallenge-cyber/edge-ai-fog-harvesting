"""AeroIon-Edge message contract (module M0).

The JSON Schemas in contract/schemas/ are the single source of truth. This module loads them and gives
Python code on the station (and the simulator, tests and tools) one way to:

- validate a message:            validate("telemetry", msg) -> list of error strings ([] means valid)
- build and parse topics:        node_topic("n01", "telemetry"), parse_topic("aeroion/n01/event")
- pack and unpack FOG_ALERT:     pack_fog_alert(...), unpack_fog_alert(data)
- read the enumerations:         STATES, EVENT_TYPES, CMD_TYPES, ...

Firmware gets the same enumerations from firmware/node/include/aeroion_contract.h, generated by
contract/generate.py. Never edit the enumerations anywhere else.
"""

import json
import struct
from pathlib import Path

from jsonschema import Draft202012Validator
from referencing import Registry, Resource

CONTRACT_DIR = Path(__file__).resolve().parent
SCHEMA_DIR = CONTRACT_DIR / "schemas"
BINARY_DIR = CONTRACT_DIR / "binary"

TOPIC_ROOT = "aeroion"
NODE_KINDS = ("telemetry", "event", "cmd", "status", "info", "wave")
STATION_KINDS = ("front","water","water_event")
KINDS = NODE_KINDS + STATION_KINDS
BROADCAST = "all"      # aeroion/all/cmd reaches every node
STATION = "station"    # aeroion/station/<kind> is published by the Raspberry Pi
SIM = "sim"            # aeroion/sim/... is simulator-only ground truth, not part of the contract


def _load_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def load_schema(name):
    return _load_json(SCHEMA_DIR / f"{name}.schema.json")


COMMON = load_schema("common")
SCHEMAS = {kind: load_schema(kind) for kind in KINDS}

SCHEMA_VERSION = COMMON["x-aeroion-version"]
SCHEMA_MAJOR, SCHEMA_MINOR = (int(p) for p in SCHEMA_VERSION.split("."))

_DEFS = COMMON["$defs"]
STATES = tuple(_DEFS["state"]["enum"])
EVENT_TYPES = tuple(_DEFS["event_type"]["enum"])
CMD_TYPES = tuple(_DEFS["cmd_type"]["enum"])
FAULT_CODES = tuple(_DEFS["fault_code"]["enum"])
ROLES = tuple(_DEFS["role"]["enum"])
BADGE_ACTIONS = tuple(_DEFS["badge_action"]["enum"])
BADGE_RESULTS = tuple(_DEFS["badge_result"]["enum"])
ACK_RESULTS = tuple(_DEFS["ack_result"]["enum"])
FOG_SOURCES = tuple(_DEFS["fog_source"]["enum"])
WAVE_TRIGGERS = tuple(_DEFS["wave_trigger"]["enum"])
WATER_EVENT_TYPES = tuple(SCHEMAS["water_event"]["properties"]["type"]["enum"])

_REGISTRY = Registry().with_resources(
    [(s["$id"], Resource.from_contents(s)) for s in (COMMON, *SCHEMAS.values())]
)
_VALIDATORS = {kind: Draft202012Validator(schema, registry=_REGISTRY) for kind, schema in SCHEMAS.items()}


def validate(kind, message):
    """Return a list of readable errors; an empty list means the message follows the contract."""
    if kind not in _VALIDATORS:
        raise ValueError(f"unknown message kind {kind!r}, expected one of {KINDS}")
    errors = sorted(_VALIDATORS[kind].iter_errors(message), key=lambda e: list(map(str, e.absolute_path)))
    return [f"{'/'.join(map(str, e.absolute_path)) or '(root)'}: {e.message}" for e in errors]


def is_valid_node_id(node_id):
    return isinstance(node_id, str) and len(node_id) == 3 and node_id[0] == "n" and node_id[1:].isdigit() \
        and node_id != "n00"


def node_topic(node_id, kind):
    if kind not in NODE_KINDS:
        raise ValueError(f"{kind!r} is not a node message kind")
    if node_id == BROADCAST and kind == "cmd":
        return f"{TOPIC_ROOT}/{BROADCAST}/cmd"
    if not is_valid_node_id(node_id):
        raise ValueError(f"invalid node id {node_id!r}")
    return f"{TOPIC_ROOT}/{node_id}/{kind}"


def station_topic(kind):
    if kind not in STATION_KINDS:
        raise ValueError(f"{kind!r} is not a station message kind")
    return f"{TOPIC_ROOT}/{STATION}/{kind}"


def parse_topic(topic):
    """Split a topic into (scope, kind). scope is a node id, 'all', 'station' or 'sim'.

    Raises ValueError for topics outside the contract.
    """
    parts = topic.split("/")
    if len(parts) != 3 or parts[0] != TOPIC_ROOT:
        raise ValueError(f"topic {topic!r} is not aeroion/<scope>/<kind>")
    _, scope, kind = parts
    if scope == SIM:
        return scope, kind
    if scope == STATION:
        if kind not in STATION_KINDS:
            raise ValueError(f"unknown station kind in {topic!r}")
        return scope, kind
    if scope == BROADCAST:
        if kind != "cmd":
            raise ValueError(f"only cmd may be broadcast, got {topic!r}")
        return scope, kind
    if not is_valid_node_id(scope):
        raise ValueError(f"invalid node id in {topic!r}")
    if kind not in NODE_KINDS:
        raise ValueError(f"unknown node kind in {topic!r}")
    return scope, kind


def node_number(node_id):
    """'n07' -> 7, used in binary messages."""
    if not is_valid_node_id(node_id):
        raise ValueError(f"invalid node id {node_id!r}")
    return int(node_id[1:])


def node_id_from_number(number):
    if not 1 <= number <= 99:
        raise ValueError(f"node number {number} out of range 1..99")
    return f"n{number:02d}"


# ---------------------------------------------------------------- FOG_ALERT (binary, node to node)

FOG_ALERT_SPEC = _load_json(BINARY_DIR / "fog_alert.json")
FOG_ALERT_MAGIC = FOG_ALERT_SPEC["magic"]
FOG_ALERT_VERSION = FOG_ALERT_SPEC["version"]
FOG_ALERT_TYPE = FOG_ALERT_SPEC["type"]
FOG_ALERT_FORMAT = "<" + "".join(f["py"] for f in FOG_ALERT_SPEC["fields"])
FOG_ALERT_SIZE = struct.calcsize(FOG_ALERT_FORMAT)
FLAG_TIME_SYNCED = 0x01
FLAG_VIRTUAL_SOURCE = 0x02


def pack_fog_alert(node_id, ts_ms, seq, fog_idx, time_synced=True, virtual_source=False):
    fog_q = max(0, min(255, round(fog_idx * 255)))
    flags = (FLAG_TIME_SYNCED if time_synced else 0) | (FLAG_VIRTUAL_SOURCE if virtual_source else 0)
    return struct.pack(FOG_ALERT_FORMAT, FOG_ALERT_MAGIC, FOG_ALERT_VERSION, FOG_ALERT_TYPE,
                       node_number(node_id), ts_ms, seq & 0xFFFF, fog_q, flags)


def unpack_fog_alert(data):
    if len(data) != FOG_ALERT_SIZE:
        raise ValueError(f"FOG_ALERT must be {FOG_ALERT_SIZE} bytes, got {len(data)}")
    names = [f["name"] for f in FOG_ALERT_SPEC["fields"]]
    raw = dict(zip(names, struct.unpack(FOG_ALERT_FORMAT, data)))
    if raw["magic"] != FOG_ALERT_MAGIC:
        raise ValueError(f"bad magic 0x{raw['magic']:02X}")
    if raw["version"] != FOG_ALERT_VERSION or raw["type"] != FOG_ALERT_TYPE:
        raise ValueError(f"unsupported FOG_ALERT version {raw['version']} / type {raw['type']}")
    return {
        "node_id": node_id_from_number(raw["node_num"]),
        "ts_ms": raw["ts_ms"],
        "seq": raw["seq"],
        "fog_idx": raw["fog_q"] / 255,
        "time_synced": bool(raw["flags"] & FLAG_TIME_SYNCED),
        "virtual_source": bool(raw["flags"] & FLAG_VIRTUAL_SOURCE),
    }
