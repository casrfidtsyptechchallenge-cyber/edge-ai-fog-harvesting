#!/usr/bin/env python3
"""Generate the firmware header and the field reference from the contract schemas.

    python contract/generate.py          # rewrite the generated files
    python contract/generate.py --check  # exit 1 if they are out of date (used by the tests)

Outputs:
    firmware/node/include/aeroion_contract.h   enumerations, topic names, FOG_ALERT struct for the ESP32
    docs/contract-reference.md                 every field of every message, with type, unit and meaning
"""

import argparse
import sys
from pathlib import Path

import aeroion_contract as ac

REPO = ac.CONTRACT_DIR.parent
HEADER_PATH = REPO / "firmware" / "node" / "include" / "aeroion_contract.h"
REFERENCE_PATH = REPO / "docs" / "contract-reference.md"

# (C type name, C constant prefix, common.schema.json $defs key)
C_ENUMS = [
    ("aeroion_state_t", "AEROION_STATE", "state"),
    ("aeroion_event_t", "AEROION_EVENT", "event_type"),
    ("aeroion_cmd_t", "AEROION_CMD", "cmd_type"),
    ("aeroion_fault_t", "AEROION_FAULT", "fault_code"),
    ("aeroion_role_t", "AEROION_ROLE", "role"),
    ("aeroion_badge_action_t", "AEROION_BADGE", "badge_action"),
    ("aeroion_badge_result_t", "AEROION_BADGE_RESULT", "badge_result"),
    ("aeroion_ack_t", "AEROION_ACK", "ack_result"),
    ("aeroion_fog_source_t", "AEROION_FOG_SOURCE", "fog_source"),
    ("aeroion_wave_trigger_t", "AEROION_WAVE_TRIGGER", "wave_trigger"),
]

GENERATED_NOTE = "GENERATED by contract/generate.py from contract/schemas/ - do not edit by hand."


# ---------------------------------------------------------------- C header

def c_header():
    defs = ac.COMMON["$defs"]
    out = [
        f"// {GENERATED_NOTE}",
        "// AeroIon-Edge message contract for the ESP32 firmware.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f'#define AEROION_SCHEMA_VERSION "{ac.SCHEMA_VERSION}"',
        f"#define AEROION_SCHEMA_MAJOR {ac.SCHEMA_MAJOR}",
        f"#define AEROION_SCHEMA_MINOR {ac.SCHEMA_MINOR}",
        "",
        "// Topics: snprintf(buf, sizeof buf, AEROION_TOPIC_FMT, node_id, AEROION_KIND_TELEMETRY)",
        f'#define AEROION_TOPIC_FMT "{ac.TOPIC_ROOT}/%s/%s"',
        f'#define AEROION_TOPIC_BROADCAST_CMD "{ac.TOPIC_ROOT}/{ac.BROADCAST}/cmd"',
    ]
    for kind in ac.NODE_KINDS:
        out.append(f'#define AEROION_KIND_{kind.upper()} "{kind}"')
    out.append("")

    for c_type, prefix, key in C_ENUMS:
        values = defs[key]["enum"]
        out.append(f"// {key}")
        out.append("typedef enum {")
        for i, v in enumerate(values):
            out.append(f"    {prefix}_{v.upper()} = {i},")
        out.append(f"    {prefix}__COUNT = {len(values)}")
        out.append(f"}} {c_type};")
        names = ", ".join(f'"{v}"' for v in values)
        array = f"{prefix}_NAMES"
        out.append(f"static const char *const {array}[{prefix}__COUNT] = {{{names}}};")
        fn = c_type[:-2] + "_name"
        out.append(f"static inline const char *{fn}({c_type} v) {{")
        out.append(f'    return ((int)v >= 0 && v < {prefix}__COUNT) ? {array}[v] : "?";')
        out.append("}")
        out.append("")

    spec = ac.FOG_ALERT_SPEC
    out += [
        f"// {spec['name']}: {spec['description']}",
        f"#define AEROION_FOG_ALERT_MAGIC 0x{spec['magic']:02X}",
        f"#define AEROION_FOG_ALERT_VERSION {spec['version']}",
        f"#define AEROION_FOG_ALERT_TYPE {spec['type']}",
        f"#define AEROION_FOG_ALERT_FLAG_TIME_SYNCED 0x{ac.FLAG_TIME_SYNCED:02X}",
        f"#define AEROION_FOG_ALERT_FLAG_VIRTUAL_SOURCE 0x{ac.FLAG_VIRTUAL_SOURCE:02X}",
        "typedef struct __attribute__((packed)) {",
    ]
    width = max(len(f["c"]) for f in spec["fields"])
    for f in spec["fields"]:
        out.append(f"    {f['c']:<{width}} {f['name']};  // {f['desc']}")
    out += [
        "} aeroion_fog_alert_t;",
        "#ifdef __cplusplus",
        f'static_assert(sizeof(aeroion_fog_alert_t) == {ac.FOG_ALERT_SIZE}, "FOG_ALERT must be {ac.FOG_ALERT_SIZE} bytes");',
        "#else",
        f'_Static_assert(sizeof(aeroion_fog_alert_t) == {ac.FOG_ALERT_SIZE}, "FOG_ALERT must be {ac.FOG_ALERT_SIZE} bytes");',
        "#endif",
        "// ESP32 is little-endian, so the struct can be sent as-is with esp_now_send().",
        "",
    ]
    return "\n".join(out)


# ---------------------------------------------------------------- Markdown reference

def resolve(prop, local_schema):
    """Follow a $ref (local or into common) and merge the referencing property's own keywords on top."""
    if "$ref" not in prop:
        return prop
    ref = prop["$ref"]
    if ref.startswith("common.schema.json#/$defs/"):
        target = ac.COMMON["$defs"][ref.rsplit("/", 1)[1]]
    elif ref.startswith("#/$defs/"):
        target = local_schema["$defs"][ref.rsplit("/", 1)[1]]
    elif ".schema.json#/$defs/" in ref:  # into another message's schema, e.g. water.schema.json#/$defs/card
        target = ac.load_schema(ref.split(".schema.json")[0])["$defs"][ref.rsplit("/", 1)[1]]
    else:
        raise ValueError(f"unsupported $ref {ref}")
    merged = dict(resolve(target, local_schema))
    merged.update({k: v for k, v in prop.items() if k != "$ref"})
    merged["x-ref-name"] = ref.rsplit("/", 1)[1]
    return merged


def type_text(p):
    if "enum" in p:
        name = p.get("x-ref-name")
        return f"enum `{name}`" if name else "enum: " + ", ".join(f"`{v}`" for v in p["enum"])
    if "const" in p:
        return f'always `"{p["const"]}"`'
    t = p.get("type", "any")
    text = " or ".join(t) if isinstance(t, list) else t
    lo, hi = p.get("minimum"), p.get("maximum", p.get("exclusiveMaximum"))
    if lo is not None or hi is not None:
        text += f" ({'' if lo is None else lo}–{'' if hi is None else hi})"
    if p.get("pattern") and t == "string":
        text += f" `{p['pattern']}`"
    if t == "array" and "items" in p:
        text += " of " + type_text(p["items"] if "$ref" not in p["items"] else resolve(p["items"], {}))
    return text


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def field_rows(schema, local_schema, prefix=""):
    rows = []
    required = set(schema.get("required", []))
    for name, raw in schema.get("properties", {}).items():
        p = resolve(raw, local_schema)
        path = prefix + name
        rows.append((path, type_text(p), p.get("x-unit", ""), "yes" if name in required else "no",
                     p.get("description", "")))
        t = p.get("type")
        if (t == "object" or (isinstance(t, list) and "object" in t)) and p.get("properties"):
            rows += field_rows(p, local_schema, prefix=path + ".")
    return rows


def table(rows):
    out = ["| Field | Type | Unit | Required | Meaning |", "|---|---|---|---|---|"]
    for r in rows:
        out.append("| " + " | ".join(cell(c) if i else f"`{cell(c)}`" for i, c in enumerate(r)) + " |")
    return out


def variant_section(kind, schema, field):
    out = []
    for name in schema["$defs"]:
        d = schema["$defs"][name]
        out.append(f"#### `{name}`")
        out.append("")
        if d.get("description"):
            out.append(d["description"])
            out.append("")
        rows = field_rows(d, schema, prefix=f"{field}.")
        out += table(rows) if rows else [f"No {field}: send `{{}}`."]
        out.append("")
    return out


def reference():
    out = [
        f"<!-- {GENERATED_NOTE} -->",
        "",
        f"# AeroIon-Edge contract reference (v{ac.SCHEMA_VERSION})",
        "",
        "Every field of every message, generated from `contract/schemas/`. "
        "Rules and conventions are in [message-schema.md](message-schema.md).",
        "",
    ]
    for kind in ac.KINDS:
        s = ac.SCHEMAS[kind]
        out += [
            f"## `{kind}`",
            "",
            s.get("description", ""),
            "",
            f"- Topic: `{s['x-topic']}`",
            f"- Direction: {s['x-direction']}",
            f"- Rate: {s['x-rate']}",
            f"- Retained: {'yes' if s['x-retain'] else 'no'}",
            "",
        ]
        out += table(field_rows(s, s))
        out.append("")
        if kind in ("event", "water_event"):
            out += ["### `data` for each event type", ""] + variant_section(kind, s, "data")
        if kind == "cmd":
            out += ["### `params` for each command type", ""] + variant_section(kind, s, "params")

    out += ["## Enumerations", ""]
    for _, _, key in C_ENUMS:
        d = ac.COMMON["$defs"][key]
        line = f"- `{key}`: " + ", ".join(f"`{v}`" for v in d["enum"])
        if d.get("description"):
            line += f" — {d['description']}"
        out.append(line)
    out.append("")

    spec = ac.FOG_ALERT_SPEC
    out += [
        f"## `{spec['name']}` (binary, node to node)",
        "",
        f"{spec['description']} Total size: {ac.FOG_ALERT_SIZE} bytes.",
        "",
        "| Field | C type | Meaning |",
        "|---|---|---|",
    ]
    for f in spec["fields"]:
        out.append(f"| `{f['name']}` | `{f['c']}` | {cell(f['desc'])} |")
    out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------- main

def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args()

    outputs = {HEADER_PATH: c_header(), REFERENCE_PATH: reference()}
    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")
    if stale:
        for path in stale:
            print(f"out of date: {path.relative_to(REPO)} (run: python contract/generate.py)", file=sys.stderr)
        return 1
    if args.check:
        print("generated files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
